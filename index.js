  /* ---------- EXIF: Orientation (to keep) plus what it reveals (to report) ---------- */
  // t = a TIFF block ("II*\0" / "MM\0*"). Reads IFD0 only: orientation, make, model, software, GPS pointer.
  function exifInfo(t) {
    const info = { orientation: 1, gps: false, make: '', model: '', software: '' };
    if (!t || t.length < 8) return info;
    const dv = new DataView(t.buffer, t.byteOffset, t.byteLength);
    const le = t[0] === 0x49;
    const str = (count, valueAt) => {
      const off = count > 4 ? dv.getUint32(valueAt, le) : valueAt;
      if (off + count > t.length) return '';
      return ascii(t.subarray(off, off + count)).replace(/\0.*$/s, '').trim().slice(0, 60);
    };
    try {
      const ifd = dv.getUint32(4, le);
      const n = dv.getUint16(ifd, le);
      for (let k = 0; k < n; k++) {
        const e = ifd + 2 + k * 12;
        const tag = dv.getUint16(e, le), type = dv.getUint16(e + 2, le), count = dv.getUint32(e + 4, le);
        if (tag === 0x0112) { const v = dv.getUint16(e + 8, le); info.orientation = v >= 1 && v <= 8 ? v : 1; }
        else if (tag === 0x8825) { const at = dv.getUint32(e + 8, le); info.gps = at + 2 <= t.length && dv.getUint16(at, le) > 0; }
        else if (type === 2 && tag === 0x010f) info.make = str(count, e + 8);
        else if (type === 2 && tag === 0x0110) info.model = str(count, e + 8);
        else if (type === 2 && tag === 0x0131) info.software = str(count, e + 8);
      }
    } catch (_) { /* truncated EXIF */ }
    return info;
  }
  function exifDetails(info) {
    const det = [];
    if (info.gps) det.push('GPS location');
    const cam = info.model && info.make && !info.model.toLowerCase().startsWith(info.make.toLowerCase().split(' ')[0]) ? info.make + ' ' + info.model : (info.model || info.make);
    if (cam) det.push('Camera: ' + cam);
    if (info.software) det.push('Software: ' + info.software);
    return det;
  }
  // True for an EXIF block that holds nothing but Orientation, such as the one orientationApp1 writes.
  // It reveals nothing, so a cleaned file re-scans as clean instead of reporting "EXIF found".
  function orientationOnly(t) {
    if (!t || t.length < 26) return false;
    const dv = new DataView(t.buffer, t.byteOffset, t.byteLength);
    const le = t[0] === 0x49;
    try {
      const ifd = dv.getUint32(4, le);
      if (dv.getUint16(ifd, le) !== 1 || dv.getUint16(ifd + 2, le) !== 0x0112) return false;
      return dv.getUint32(ifd + 14, le) === 0;
    } catch (_) { return false; }
  }
  function exifOrientation(payload) {
    // payload = "Exif\0\0" + TIFF
    if (!startsWith(payload, 'Exif\0\0') || payload.length < 14) return 1;
    return exifInfo(payload.subarray(6)).orientation;
  }
  // Minimal APP1 with only Orientation: no camera, time, GPS or software.
  function orientationApp1(v) {
    const p = new Uint8Array(32);
    p.set([0x45, 0x78, 0x69, 0x66, 0, 0]);                 // "Exif\0\0"
    p.set([0x4d, 0x4d, 0x00, 0x2a, 0, 0, 0, 8], 6);       // big-endian TIFF, IFD0 at 8
    p.set([0, 1], 14);                                     // 1 entry
    p.set([0x01, 0x12, 0, 3, 0, 0, 0, 1, 0, v, 0, 0], 16); // Orientation SHORT x1
    // next-IFD offset (bytes 28..31) stays 0
    const seg = new Uint8Array(4 + p.length);
    seg.set([0xff, 0xe1, 0, p.length + 2]);
    seg.set(p, 4);
    return seg;
  }

