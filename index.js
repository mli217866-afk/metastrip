  // Parse IFD0, the Exif IFD, the GPS IFD and IFD1 (thumbnail). Each entry: tag, type, count, entry offset,
  // value offset (-1 when it points outside the block) and value size.
  function exifTree(t) {
    if (!t || t.length < 8 || !(startsWith(t, 'II*\0') || startsWith(t, 'MM\0*'))) return null;
    const dv = new DataView(t.buffer, t.byteOffset, t.byteLength);
    const le = t[0] === 0x49;
    const ifd = (off) => {
      if (!off || off + 2 > t.length) return null;
      const n = dv.getUint16(off, le);
      if (off + 2 + n * 12 + 4 > t.length) return null;
      const entries = [];
      for (let k = 0; k < n; k++) {
        const e = off + 2 + k * 12;
        const tag = dv.getUint16(e, le), type = dv.getUint16(e + 2, le), count = dv.getUint32(e + 4, le);
        const size = (EXIF_SIZE[type] || 0) * count;
        let at = size > 4 ? dv.getUint32(e + 8, le) : e + 8;
        if (!EXIF_SIZE[type] || at + size > t.length) at = -1;
        entries.push({ tag, type, count, entry: e, at, size });
      }
      return { off, entries, next: dv.getUint32(off + 2 + n * 12, le) };
    };
    try {
      const ifd0 = ifd(dv.getUint32(4, le));
      if (!ifd0) return null;
      const ptr = (tag) => { const e = ifd0.entries.find((x) => x.tag === tag); return e && e.at >= 0 ? dv.getUint32(e.at, le) : 0; };
      return { t, dv, le, ifd0, exif: ifd(ptr(0x8769)), gps: ifd(ptr(0x8825)), ifd1: ifd(ifd0.next) };
    } catch (_) { return null; }
  }
  function exifValues(tr, e) {
    const { t, dv, le } = tr;
    if (e.at < 0) return [];
    const out = [];
    for (let k = 0; k < Math.min(e.count, 64); k++) {
      const p = e.at + k * EXIF_SIZE[e.type];
      switch (e.type) {
        case 1: case 7: out.push(t[p]); break;
        case 6: out.push(dv.getInt8(p)); break;
        case 3: out.push(dv.getUint16(p, le)); break;
        case 8: out.push(dv.getInt16(p, le)); break;
        case 4: out.push(dv.getUint32(p, le)); break;
        case 9: out.push(dv.getInt32(p, le)); break;
        case 5: { const n = dv.getUint32(p, le), q = dv.getUint32(p + 4, le); out.push(q ? n / q : 0); break; }
        case 10: { const n = dv.getInt32(p, le), q = dv.getInt32(p + 4, le); out.push(q ? n / q : 0); break; }
        case 11: out.push(dv.getFloat32(p, le)); break;
        case 12: out.push(dv.getFloat64(p, le)); break;
        default: break;
      }
    }
    return out;
  }
  const num = (v) => String(Math.round(v * 1000) / 1000);
  const ENUMS = {
    Orientation: { 1: 'Normal', 2: 'Mirrored', 3: 'Rotated 180°', 4: 'Mirrored vertically', 5: 'Mirrored, rotated 90° CCW', 6: 'Rotated 90° CW', 7: 'Mirrored, rotated 90° CW', 8: 'Rotated 90° CCW' },
    ExposureProgram: { 0: 'Not defined', 1: 'Manual', 2: 'Program', 3: 'Aperture priority', 4: 'Shutter priority', 5: 'Creative', 6: 'Action', 7: 'Portrait', 8: 'Landscape' },
    MeteringMode: { 0: 'Unknown', 1: 'Average', 2: 'Center-weighted', 3: 'Spot', 4: 'Multi-spot', 5: 'Pattern', 6: 'Partial' },
    WhiteBalance: { 0: 'Auto', 1: 'Manual' }, ExposureMode: { 0: 'Auto', 1: 'Manual', 2: 'Auto bracket' },
    ColorSpace: { 1: 'sRGB', 65535: 'Uncalibrated' }, ResolutionUnit: { 1: 'None', 2: 'inches', 3: 'cm' },
    SceneCaptureType: { 0: 'Standard', 1: 'Landscape', 2: 'Portrait', 3: 'Night' }, GPSAltitudeRef: { 0: 'Above sea level', 1: 'Below sea level' }
  };
  function exifText(tr, e, name, refs) {
    const { t } = tr;
    if (e.at < 0) return '(unreadable)';
    if (e.type === 2) return ascii(t.subarray(e.at, e.at + e.size)).replace(/\0.*$/s, '').trim().slice(0, 120);
    if (name === 'MakerNote') return e.size + ' bytes of maker-specific data';
    if (name === 'ExifVersion' || name === 'FlashpixVersion') return ascii(t.subarray(e.at, e.at + e.size));
    if (name === 'UserComment') return ascii(t.subarray(e.at + 8, e.at + e.size)).replace(/\0+$/, '').trim().slice(0, 120) || '(empty)';
    if (e.type === 7) return e.size + ' bytes';
    const v = exifValues(tr, e);
    if (!v.length) return '';
    if (ENUMS[name] && v.length === 1) return ENUMS[name][v[0]] || String(v[0]);
    if (name === 'GPSLatitude' || name === 'GPSLongitude') {
      const deg = v[0] + (v[1] || 0) / 60 + (v[2] || 0) / 3600;
      return deg.toFixed(6) + '° ' + (refs[name + 'Ref'] || '');
    }
    if (name === 'GPSTimeStamp') return v.map((x) => String(Math.floor(x)).padStart(2, '0')).join(':') + ' UTC';
    if (name === 'GPSAltitude') return num(v[0]) + ' m';
    if (name === 'GPSVersionID') return v.join('.');
    if (name === 'ExposureTime') return (v[0] > 0 && v[0] < 1 ? '1/' + Math.round(1 / v[0]) : num(v[0])) + ' s';
    if (name === 'FNumber') return 'f/' + num(v[0]);
    if (name === 'FocalLength' || name === 'FocalLengthIn35mmFilm') return num(v[0]) + ' mm';
    if (name === 'ExposureBiasValue') return (v[0] > 0 ? '+' : '') + num(v[0]) + ' EV';
    if (name === 'Flash') return v[0] & 1 ? 'Fired' : 'Did not fire';
    if (name === 'LensSpecification' && v.length === 4) return num(v[0]) + '–' + num(v[1]) + ' mm, f/' + num(v[2]) + '–' + num(v[3]);
    return v.slice(0, 8).map(num).join(', ') + (v.length > 8 ? ', …' : '');
  }
  // Every field in a TIFF block, as { group, name, value }. Pointers are structure, not data, so they are left out.
  function exifFields(t) {
    const tr = exifTree(t);
    if (!tr) return [];
    const fields = [];
    const list = (dir, names, gps) => {
      if (!dir) return;
      const refs = {};
      if (gps) for (const e of dir.entries) if (e.type === 2 && names[e.tag] && /Ref$/.test(names[e.tag])) refs[names[e.tag]] = exifText(tr, e, '', {});
      for (const e of dir.entries) {
        if (!gps && POINTERS.has(e.tag)) continue;
        const name = names[e.tag] || (gps ? 'GPS tag ' : 'Tag ') + hex(e.tag);
        fields.push({ group: gps ? 'Location' : groupOf(name), name, value: exifText(tr, e, name, refs) });
      }
    };
    list(tr.ifd0, EXIF_TAGS, false);
    list(tr.exif, EXIF_TAGS, false);
    list(tr.gps, GPS_TAGS, true);
    if (tr.ifd1) {
      const len = tr.ifd1.entries.find((e) => e.tag === 0x0202);
      fields.push({ group: 'Image', name: 'Thumbnail', value: 'embedded preview image' + (len ? ', ' + exifValues(tr, len)[0] + ' bytes' : '') });
    }
    return fields;
  }
  // Whether a field survives cleaning in the given mode.
  // kind matters for 'all': JPEG keeps a minimal Orientation block and HEIF keeps rotation as a property;
  // PNG and WebP have no such place, so Orientation goes with the rest.
  function exifFieldKept(field, mode, kind) {
    if (mode === 'gps') return field.group !== 'Location';
    if (mode === 'camera') return CAMERA_KEEP.has(field.name);
    return field.name === 'Orientation' && kind !== 'png' && kind !== 'webp';
  }
  // 'gps': same bytes with the GPS entries and their values zeroed and the GPS directory emptied.
  // Nothing moves, so maker notes and other offset-based data stay valid.
  function exifWithoutGps(t) {
    const tr = exifTree(t);
    const out = t.slice();
    if (!tr || !tr.gps) return out;
    for (const e of tr.gps.entries) if (e.at >= 0 && e.size > 4) out.fill(0, e.at, e.at + e.size);
    out.fill(0, tr.gps.off, tr.gps.off + 2 + tr.gps.entries.length * 12 + 4);
    return out;
  }
  // 'camera': a fresh big-endian TIFF with IFD0 and an Exif IFD holding only CAMERA_KEEP fields.
  function exifCameraOnly(t) {
    const tr = exifTree(t);
    if (!tr) return null;
    const raw = (e) => {
      const b = t.slice(e.at, e.at + e.size), u = EXIF_UNIT[e.type];
      if (tr.le && u > 1) for (let p = 0; p + u <= b.length; p += u) b.subarray(p, p + u).reverse();
      return b;
    };
    const pick = (dir) => (dir ? dir.entries : []).filter((e) => e.at >= 0 && CAMERA_KEEP.has(EXIF_TAGS[e.tag]))
      .map((e) => ({ tag: e.tag, type: e.type, count: e.count, data: raw(e) }));
    const l0 = pick(tr.ifd0), l1 = pick(tr.exif);
    if (!l0.length && !l1.length) return null;
    const s0 = 2 + 12 * (l0.length + (l1.length ? 1 : 0)) + 4;
    const exifAt = 8 + s0;
    if (l1.length) l0.push({ tag: 0x8769, type: 4, count: 1, data: Uint8Array.of(exifAt >>> 24, (exifAt >>> 16) & 255, (exifAt >>> 8) & 255, exifAt & 255) });
    l0.sort((a, b) => a.tag - b.tag);
    l1.sort((a, b) => a.tag - b.tag);
    let dataAt = exifAt + (l1.length ? 2 + 12 * l1.length + 4 : 0);
    const w = writer().bytes(Uint8Array.of(0x4d, 0x4d, 0, 0x2a)).uint(8, 4);
    const blobs = [];
    const dir = (list) => {
      w.uint(list.length, 2);
      for (const e of list) {
        w.uint(e.tag, 2).uint(e.type, 2).uint(e.count, 4);
        if (e.data.length <= 4) { const p = new Uint8Array(4); p.set(e.data); w.bytes(p); }
        else { w.uint(dataAt, 4); blobs.push(e.data); dataAt += e.data.length + (e.data.length & 1); }
      }
      w.uint(0, 4);
    };
    dir(l0);
    if (l1.length) dir(l1);
    for (const b of blobs) { w.bytes(b); if (b.length & 1) w.bytes(new Uint8Array(1)); }
    return w.done();
  }
  // The EXIF block to write back for a mode, or null to remove it.
  function exifFor(t, mode) {
    if (mode === 'gps') return exifTree(t) ? exifWithoutGps(t) : null;
    if (mode === 'camera') return exifCameraOnly(t);
    return null;
  }
  const EXIF_KEPT_LABEL = { gps: 'EXIF (GPS removed)', camera: 'EXIF (camera and copyright only)' };
  const EXIF_HEAD = Uint8Array.of(0x45, 0x78, 0x69, 0x66, 0, 0); // "Exif\0\0"
  const CRC_TABLE = (() => {
    const tb = new Uint32Array(256);
    for (let n = 0; n < 256; n++) { let c = n; for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1; tb[n] = c >>> 0; }
    return tb;
  })();
  function pngChunk(type, body) {
    const out = new Uint8Array(12 + body.length);
    const dv = new DataView(out.buffer);
    dv.setUint32(0, body.length);
    for (let k = 0; k < 4; k++) out[4 + k] = type.charCodeAt(k);
    out.set(body, 8);
    let c = 0xffffffff;
    for (let k = 4; k < 8 + body.length; k++) c = CRC_TABLE[(c ^ out[k]) & 255] ^ (c >>> 8);
    dv.setUint32(8 + body.length, (c ^ 0xffffffff) >>> 0);
    return out;
  }

  /* ---------- JPEG ---------- */
  function stripJpeg(d, opts) {
    const kept = [d.subarray(0, 2)];
    const found = [];
    const add = (type, detail) => found.push({ type, detail: detail || [] });
    const rc = receipt();
    let orientation = 1;
    let exifList = null;
    let i = 2;
    let eoi = -1;

    while (i < d.length) {
      if (d[i] !== 0xff) throw new Error('Corrupt JPEG (bad marker at ' + i + ')');
      let j = i;
      while (j < d.length && d[j] === 0xff) j++;
      const m = d[j];
      if (m === 0xd9) { eoi = j + 1; kept.push(d.subarray(i, eoi)); rc.image(i, eoi - i); break; }
      if (m === 0x01 || (m >= 0xd0 && m <= 0xd7)) { kept.push(d.subarray(i, j + 1)); rc.image(i, j + 1 - i); i = j + 1; continue; }
      const len = (d[j + 1] << 8) | d[j + 2];
      const end = j + 1 + len;
      if (end > d.length) throw new Error('Corrupt JPEG (segment runs past end of file)');
      const payload = d.subarray(j + 3, end);

      if (m === 0xda) {
        // SOS: header, then entropy-coded data up to the next real marker.
        let k = end;
        while (k < d.length - 1) {
          if (d[k] === 0xff) {
            const n = d[k + 1];
            if (n !== 0x00 && n !== 0xff && !(n >= 0xd0 && n <= 0xd7)) break;
          }
          k++;
        }
        kept.push(d.subarray(i, k));
        rc.image(i, k - i);
        i = k;
        continue;
      }

      let drop = null;
      let orientationBlock = false;
      if (m === 0xe1) {
        if (startsWith(payload, 'Exif\0\0') && orientationOnly(payload.subarray(6))) {
          orientationBlock = true;
        } else if (startsWith(payload, 'Exif\0\0')) {
          const tiff = payload.subarray(6);
          if (!exifList) exifList = exifFields(tiff);
          const repl = exifFor(tiff, opts.exif);
          if (repl) {
            // Partial removal: the block stays, rewritten.
            const det = exifDetails(exifInfo(tiff));
            add('EXIF', det);
            const body = concat([EXIF_HEAD, repl]);
            const seg = new Uint8Array(4 + body.length);
            seg.set([0xff, 0xe1, (body.length + 2) >> 8, (body.length + 2) & 255]);
            seg.set(body, 4);
            kept.push(seg);
            rc.meta(i, mk(m), EXIF_KEPT_LABEL[opts.exif], end - i, false, det.join(' · '));
            i = end;
            continue;
          }
          drop = 'EXIF';
          const info = exifInfo(tiff);
          orientation = info.orientation;
          const det = exifDetails(info);
          if (orientation !== 1) det.push('rotation kept');
          add('EXIF', det);
        } else if (startsWith(payload, 'http://ns.adobe.com/xap/1.0/')) {
          drop = 'XMP';
          const txt = ascii(payload);
          const det = aiSignals(txt);
          if (/hdrgm:/i.test(txt)) det.push('HDR gain map info');
          add('XMP', det);
        } else if (startsWith(payload, 'http://ns.adobe.com/xmp/extension/')) {
          drop = 'XMP';
          add('XMP (extended)', aiSignals(ascii(payload)));
        }
      } else if (m === 0xe2 && startsWith(payload, 'MPF\0')) {
        drop = 'MPF';
        add('Multi-picture index (MPF)');
      } else if (m === 0xeb && startsWith(payload, 'JP')) {
        drop = 'C2PA';
        add('C2PA / JUMBF', aiSignals(ascii(payload)));
      } else if (m === 0xed) {
        drop = 'IPTC';
        // Skip the fixed "Photoshop 3.0\0" header so it isn't reported as a tool mention.
        add('IPTC / Photoshop', aiSignals(ascii(startsWith(payload, 'Photoshop 3.0\0') ? payload.subarray(14) : payload)));
      } else if (m === 0xfe) {
        drop = 'COM';
        add('Comment');
      }

      if (drop) {
        const f = found[found.length - 1];
        rc.meta(i, mk(m), f.type, end - i, true, f.detail.join(' · '));
      } else {
        kept.push(d.subarray(i, end));
        if (orientationBlock) rc.meta(i, mk(m), 'EXIF (orientation only)', end - i, false, 'Orientation kept');
        else if (m === 0xe0) rc.meta(i, mk(m), 'JFIF header', end - i, false);
        else if (m === 0xe2 && startsWith(payload, 'ICC_PROFILE')) rc.meta(i, mk(m), 'ICC colour profile', end - i, false);
        else if (m === 0xee) rc.meta(i, mk(m), 'Adobe colour info', end - i, false);
        else if (m >= 0xe0 && m <= 0xef) rc.meta(i, mk(m), 'APP' + (m - 0xe0), end - i, false);
        else rc.image(i, end - i);
      }
      i = end;
    }
    if (eoi < 0) throw new Error('Corrupt JPEG (no end-of-image marker)');

    if (eoi < d.length) {
      const tail = d.subarray(eoi);
      const det = [];
      if (tail.indexOf(0xff) === 0 && tail[1] === 0xd8) det.push('embedded image (e.g. HDR gain map)');
      if (ascii(tail.subarray(Math.max(0, tail.length - 64))).includes('SEFT')) det.push('Samsung edit trailer');
      det.push(...aiSignals(ascii(tail)));
      add('Data after image end', det);
      rc.meta(eoi, '', 'Data after image end', d.length - eoi, true, det.join(' · '));
    }

    if (orientation !== 1) {
      // Put it right after JFIF (APP0) if present, else right after SOI.
      const at = kept.length > 1 && kept[1][1] === 0xe0 ? 2 : 1;
      kept.splice(at, 0, orientationApp1(orientation));
    }
    return { bytes: concat(kept), found, orientation, segments: rc.rows, exifFields: exifList || [] };
  }

  /* ---------- PNG ---------- */
  const PNG_DROP = new Set(['tEXt', 'iTXt', 'zTXt', 'eXIf', 'caBX', 'tIME']);
  function stripPng(d, opts) {
    let exifList = null;
    const dv = new DataView(d.buffer, d.byteOffset, d.byteLength);
    const kept = [d.subarray(0, 8)];
    const found = [];
    const rc = receipt();
    let i = 8;
    let ended = false;
    while (i + 12 <= d.length) {
      const len = dv.getUint32(i);
      const type = ascii(d.subarray(i + 4, i + 8));
      const end = i + 12 + len;
      if (end > d.length) throw new Error('Corrupt PNG (chunk runs past end of file)');
      if (type === 'eXIf' && !exifList) exifList = exifFields(d.subarray(i + 8, i + 8 + len));
      const pngExif = type === 'eXIf' ? exifFor(d.subarray(i + 8, i + 8 + len), opts.exif) : null;
      if (pngExif) {
        const det = exifDetails(exifInfo(d.subarray(i + 8, i + 8 + len)));
        found.push({ type: 'EXIF', detail: det });
        kept.push(pngChunk('eXIf', pngExif));
        rc.meta(i, type, EXIF_KEPT_LABEL[opts.exif], end - i, false, det.join(' · '));
      } else if (PNG_DROP.has(type)) {
        const body = d.subarray(i + 8, i + 8 + len);
        const key = type === 'caBX' || type === 'tIME' ? '' : ascii(body.subarray(0, Math.max(0, body.indexOf(0))));
        let label = type;
        const det = [];
        if (type === 'caBX') label = 'C2PA / JUMBF';
        else if (type === 'eXIf') { label = 'EXIF'; det.push(...exifDetails(exifInfo(body))); }
        else if (type === 'tIME') label = 'Timestamp';
        else if (key === 'XML:com.adobe.xmp') label = 'XMP';
        else if (key === 'parameters') { label = 'Text: parameters'; det.push('Stable Diffusion prompt'); }
        else if (key === 'prompt' || key === 'workflow') { label = 'Text: ' + key; det.push('ComfyUI prompt/workflow'); }
        else if (key) label = 'Text: ' + key;
        if (type !== 'zTXt' && type !== 'tIME') det.push(...aiSignals(ascii(body)));
        found.push({ type: label, detail: det });
        rc.meta(i, type, label, end - i, true, det.join(' · '));
      } else {
        kept.push(d.subarray(i, end));
        if (type === 'iCCP') rc.meta(i, type, 'ICC colour profile', end - i, false);
        else rc.image(i, end - i);
      }
      i = end;
      if (type === 'IEND') { ended = true; break; }
    }
    if (!ended) throw new Error('Corrupt PNG (no IEND chunk)');
    if (i < d.length) {
      found.push({ type: 'Data after image end', detail: [] });
      rc.meta(i, '', 'Data after image end', d.length - i, true);
    }
    return { bytes: concat(kept), found, segments: rc.rows, exifFields: exifList || [] };
  }

  /* ---------- WebP ---------- */
  const WEBP_DROP = { 'EXIF': 'EXIF', 'XMP ': 'XMP', 'C2PA': 'C2PA / JUMBF' };
  function stripWebp(d, opts) {
    let exifList = null, exifKept = false;
    const kept = [];
    const found = [];
    const rc = receipt();
    let vp8x = null;
    let i = 12;
    const riffEnd = Math.min(d.length, 8 + (d[4] | (d[5] << 8) | (d[6] << 16) | (d[7] << 24)) >>> 0);
    while (i + 8 <= riffEnd) {
      const id = ascii(d.subarray(i, i + 4));
      const size = (d[i + 4] | (d[i + 5] << 8) | (d[i + 6] << 16) | (d[i + 7] << 24)) >>> 0;
      const end = i + 8 + size + (size & 1);
      if (end > d.length + 1) throw new Error('Corrupt WebP (chunk runs past end of file)');
      const wb = d.subarray(i + 8, i + 8 + size);
      const wt = id === 'EXIF' ? (startsWith(wb, 'Exif\0\0') ? wb.subarray(6) : wb) : null;
      if (wt && !exifList) exifList = exifFields(wt);
      // Some writers put "Exif\0\0" before the TIFF block; keep whichever form the file used.
      const webpRepl = wt ? exifFor(wt, opts.exif) : null;
      const webpExif = webpRepl && wt !== wb ? concat([EXIF_HEAD, webpRepl]) : webpRepl;
      if (webpExif) {
        const det = exifDetails(exifInfo(wt));
        found.push({ type: 'EXIF', detail: det });
        const c = new Uint8Array(8 + webpExif.length + (webpExif.length & 1));
        c.set([0x45, 0x58, 0x49, 0x46]);
        new DataView(c.buffer).setUint32(4, webpExif.length, true);
        c.set(webpExif, 8);
        kept.push(c);
        exifKept = true;
        rc.meta(i, id, EXIF_KEPT_LABEL[opts.exif], end - i, false, det.join(' · '));
      } else if (WEBP_DROP[id]) {
        const body = wb;
        const det = id === 'EXIF' ? exifDetails(exifInfo(startsWith(body, 'Exif\0\0') ? body.subarray(6) : body)) : aiSignals(ascii(body));
        found.push({ type: WEBP_DROP[id], detail: det });
        rc.meta(i, id.trim(), WEBP_DROP[id], end - i, true, det.join(' · '));
      } else {
        const c = d.slice(i, Math.min(end, d.length));
        if (id === 'VP8X') vp8x = c;
        kept.push(c);
        if (id === 'ICCP') rc.meta(i, id, 'ICC colour profile', c.length, false);
        else rc.image(i, c.length);
      }
      i = end;
    }
    // VP8X flags byte: ICC 0x20, alpha 0x10, EXIF 0x08, XMP 0x04, anim 0x02
    if (vp8x) vp8x[8] &= exifKept ? ~0x04 : ~0x0c;
    const body = concat(kept);
    const head = new Uint8Array(12);
    head.set([0x52, 0x49, 0x46, 0x46]);
    new DataView(head.buffer).setUint32(4, 4 + body.length, true);
    head.set([0x57, 0x45, 0x42, 0x50], 8);
    return { bytes: concat([head, body]), found, segments: rc.rows, exifFields: exifList || [] };
  }

  /* ---------- HEIF (HEIC, AVIF): ISO BMFF boxes ---------- */
  // Metadata lives in "items": Exif and XMP/C2PA ("mime") items whose bytes sit in mdat (or idat), found
  // through the iloc table. Removing them means dropping their entries from iinf/iloc/iref/ipma, cutting
  // their bytes out, and moving every remaining item's offsets so they point at the same bytes as before.
  // Image items (tiles, thumbnails, depth, gain maps) and all properties (colour profile, rotation, size)
  // are copied untouched. Rotation is the irot/imir property, not EXIF, so it survives.
  const C2PA_UUID = 'd8fec3d61b0e483c92975828877ec481';
  const XMP_UUID = 'be7acfcb97a942e89c71999491e3afac';
  const toHex = (u8) => Array.from(u8, (b) => b.toString(16).padStart(2, '0')).join('');

  function readUint(dv, at, size) {
    if (size === 0) return 0;
    if (size === 1) return dv.getUint8(at);
    if (size === 2) return dv.getUint16(at);
    if (size === 4) return dv.getUint32(at);
    if (size === 8) {
      const v = dv.getUint32(at) * 4294967296 + dv.getUint32(at + 4);
      if (!Number.isSafeInteger(v)) throw new Error('Corrupt HEIF (offset too large)');
      return v;
    }
    throw new Error('Corrupt HEIF (field size ' + size + ')');
  }
  // Big-endian writer that grows as needed.
  function writer() {
    let buf = new Uint8Array(256), dv = new DataView(buf.buffer), n = 0;
    const room = (k) => { if (n + k <= buf.length) return; const b = new Uint8Array(Math.max(buf.length * 2, n + k)); b.set(buf); buf = b; dv = new DataView(buf.buffer); };
    const w = {
      uint(v, size) {
        room(size);
        if (size === 1) dv.setUint8(n, v);
        else if (size === 2) dv.setUint16(n, v);
        else if (size === 4) dv.setUint32(n, v);
        else if (size === 8) { dv.setUint32(n, Math.floor(v / 4294967296)); dv.setUint32(n + 4, v >>> 0); }
        else if (size !== 0) throw new Error('bad field size');
        if (size && v >= 2 ** (8 * size)) throw new Error('HEIF value does not fit its field');
        n += size; return w;
      },
      bytes(u8) { room(u8.length); buf.set(u8, n); n += u8.length; return w; },
      str(s) { return w.bytes(Uint8Array.from(s, (c) => c.charCodeAt(0))); },
      done: () => buf.slice(0, n)
    };
    return w;
  }
  // A box: size + type (+ uuid) + payload. Uses a 64-bit size only when it has to.
  function box(type, payload) {
    const small = 8 + payload.length <= 0xffffffff;
    const w = writer();
    if (small) w.uint(8 + payload.length, 4).str(type);
    else w.uint(1, 4).str(type).uint(16 + payload.length, 8);
    return concat([w.done(), payload]);
  }
  function boxes(d, start, end) {
    const out = [];
    const dv = new DataView(d.buffer, d.byteOffset, d.byteLength);
    let i = start;
    while (i + 8 <= end) {
      let size = dv.getUint32(i);
      const type = ascii(d.subarray(i + 4, i + 8));
      let hdr = 8;
      if (size === 1) { size = readUint(dv, i + 8, 8); hdr = 16; } else if (size === 0) size = end - i;
      if (type === 'uuid') hdr += 16;
      if (size < hdr || i + size > end) throw new Error('Corrupt HEIF (box ' + type + ' runs past its parent)');
      out.push({ type, start: i, end: i + size, body: i + hdr, uuid: type === 'uuid' ? toHex(d.subarray(i + hdr - 16, i + hdr)) : '' });
      i += size;
    }
    return out;
  }
  const cstr = (d, at, end) => { let k = at; while (k < end && d[k] !== 0) k++; return { s: ascii(d.subarray(at, k)), next: Math.min(end, k + 1) }; };

  function stripHeif(d, keep) {
    const dv = new DataView(d.buffer, d.byteOffset, d.byteLength);
    const top = boxes(d, 0, d.length);
    if (top.some((b) => b.type === 'moov')) throw new Error('HEIF image sequences are not supported. Single photos only.');
    const metaBox = top.find((b) => b.type === 'meta');
    if (!metaBox) throw new Error('Corrupt HEIF (no meta box)');
    const metaHead = d.subarray(metaBox.body, metaBox.body + 4); // FullBox version + flags
    const kids = boxes(d, metaBox.body + 4, metaBox.end);
    const kid = (t) => kids.find((b) => b.type === t);

    // iinf: which items exist and what they are
    const items = new Map(); // id -> { type, contentType, raw }
    const iinf = kid('iinf');
    if (!iinf) throw new Error('Corrupt HEIF (no item info)');
    const iinfVer = d[iinf.body];
    const iinfCountSize = iinfVer === 0 ? 2 : 4;
    for (const e of boxes(d, iinf.body + 4 + iinfCountSize, iinf.end)) {
      if (e.type !== 'infe') continue;
      const v = d[e.body];
      let at = e.body + 4, id, type = '', contentType = '';
      if (v >= 2) {
        id = v === 2 ? dv.getUint16(at) : dv.getUint32(at); at += v === 2 ? 2 : 4;
        at += 2; // protection index
        type = ascii(d.subarray(at, at + 4)); at += 4;
        at = cstr(d, at, e.end).next; // name
        if (type === 'mime') contentType = cstr(d, at, e.end).s;
      } else {
        id = dv.getUint16(at); at += 4;
        at = cstr(d, at, e.end).next;
        contentType = cstr(d, at, e.end).s;
        type = contentType ? 'mime' : '';
      }
      items.set(id, { type, contentType, raw: d.subarray(e.start, e.end) });
    }
    const label = (it) => {
      if (it.type === 'Exif') return 'EXIF';
      if (it.type === 'c2pa' || /c2pa/i.test(it.contentType)) return 'C2PA / JUMBF';
      if (it.type === 'mime' && /rdf\+xml|xmp/i.test(it.contentType)) return 'XMP';
      return null;
    };

    // iloc: where each item's bytes are
    const iloc = kid('iloc');
    if (!iloc) throw new Error('Corrupt HEIF (no item locations)');
    const lv = d[iloc.body];
    let at = iloc.body + 4;
    const offSize = d[at] >> 4, lenSize = d[at] & 15, baseSize = d[at + 1] >> 4, idxSize = lv >= 1 ? d[at + 1] & 15 : 0;
    at += 2;
    const locCount = lv < 2 ? dv.getUint16(at) : dv.getUint32(at); at += lv < 2 ? 2 : 4;
    const locs = [];
    for (let k = 0; k < locCount; k++) {
      const id = lv < 2 ? dv.getUint16(at) : dv.getUint32(at); at += lv < 2 ? 2 : 4;
      let method = 0;
      if (lv >= 1) { method = dv.getUint16(at) & 15; at += 2; }
      const dataRef = dv.getUint16(at); at += 2;
      const base = readUint(dv, at, baseSize); at += baseSize;
      const n = dv.getUint16(at); at += 2;
      const extents = [];
      for (let x = 0; x < n; x++) {
        const index = readUint(dv, at, idxSize); at += idxSize;
        const off = readUint(dv, at, offSize); at += offSize;
        const len = readUint(dv, at, lenSize); at += lenSize;
        extents.push({ index, off, len });
      }
      locs.push({ id, method, dataRef, base, extents });
    }
    const idat = kid('idat');
    const idatStart = idat ? idat.body : 0;

    // What to remove
    const removeIds = new Set();
    const exifItems = [];
    const found = [];
    const rc = receipt();
    const dataOf = (loc) => concat(loc.extents.map((e) => {
      const s = (loc.method === 1 ? idatStart : 0) + loc.base + e.off;
      return d.subarray(s, s + e.len);
    }));
    for (const loc of locs) {
      const it = items.get(loc.id);
      const name = it && label(it);
      if (!name) continue;
      if (loc.method === 2 || loc.dataRef !== 0) throw new Error('Unsupported HEIF layout (metadata stored by reference)');
      if (loc.extents.some((e) => e.len === 0)) throw new Error('Unsupported HEIF layout (open-ended metadata item)');
      const body = dataOf(loc);
      const first = (loc.method === 1 ? idatStart : 0) + loc.base + loc.extents[0].off;
      let det = [];
      if (name === 'EXIF') {
        let tiffAt = body.length >= 4 ? 4 + new DataView(body.buffer, body.byteOffset).getUint32(0) : 0;
        if (startsWith(body.subarray(tiffAt), 'Exif\0\0')) tiffAt += 6;
        const tiff = body.subarray(tiffAt);
        det = exifDetails(exifInfo(tiff));
        const ranges = loc.extents.map((e) => { const s = (loc.method === 1 ? idatStart : 0) + loc.base + e.off; return [s, s + e.len]; });
        exifItems.push({ id: loc.id, ranges, tiffAt, tiff });
      } else {
        det = aiSignals(ascii(body));
        if (name === 'XMP' && /HDRGainMap|hdrgm:/i.test(ascii(body))) det.push('HDR gain map info');
      }
      found.push({ type: name, detail: det });
      if (keep && keep.has(loc.id)) { rc.meta(first, it.type, keep.get(loc.id), body.length, false, det.join(' · ')); continue; }
      removeIds.add(loc.id);
      rc.meta(first, it.type === 'mime' ? 'mime' : it.type, name, body.length, true, det.join(' · '));
    }
    // Items listed in iinf with no location are dropped too (nothing to cut, but nothing to keep).
    for (const [id, it] of items) if (label(it) && !locs.some((l) => l.id === id)) removeIds.add(id);

    // Byte ranges to cut, per container (file for method 0, idat for method 1); never cut bytes a kept item uses.
    const cutFile = [], cutIdat = [], keepFile = [], keepIdat = [];
    for (const loc of locs) {
      for (const e of loc.extents) {
        const r = [loc.base + e.off, loc.base + e.off + e.len];
        if (removeIds.has(loc.id)) (loc.method === 1 ? cutIdat : cutFile).push(r);
        else if (loc.method !== 2 && e.len > 0) (loc.method === 1 ? keepIdat : keepFile).push(r);
      }
    }
    // Bytes a metadata item shares with a kept item stay (some writers let the two touch); the rest is cut.
    const minus = (r, keep) => keep.reduce((parts, [ka, kb]) => parts.flatMap(([a, b]) =>
      kb <= a || ka >= b ? [[a, b]] : [[a, Math.min(b, ka)], [Math.max(a, kb), b]].filter(([x, y]) => y > x)), [r]);
    const cutsFile = cutFile.flatMap((r) => minus(r, keepFile)).sort((a, b) => a[0] - b[0]);
    const cutsIdat = cutIdat.flatMap((r) => minus(r, keepIdat)).sort((a, b) => a[0] - b[0]);
    // A kept item with length 0 runs to the end of its container; cutting after its start would change it.
    for (const loc of locs) {
      if (removeIds.has(loc.id) || loc.method === 2) continue;
      for (const e of loc.extents) {
        const s = loc.base + e.off;
        if (e.len === 0 && (loc.method === 1 ? cutsIdat : cutsFile).some((r) => r[0] >= s)) throw new Error('Unsupported HEIF layout (open-ended image item)');
      }
    }
    const mdats = top.filter((b) => b.type === 'mdat');
    for (const r of cutsFile) {
      if (!mdats.some((m) => r[0] >= m.body && r[1] <= m.end)) throw new Error('Unsupported HEIF layout (metadata outside the media data)');
    }

    // Descriptive item properties: user description (title, caption, tags) and creation/modification
    // times. They are never needed to decode or display the image, so they go too and ipma is renumbered.
    const iprpBox = kid('iprp');
    const ipco = iprpBox && boxes(d, iprpBox.body, iprpBox.end).find((b) => b.type === 'ipco');
    const props = ipco ? boxes(d, ipco.body, ipco.end) : [];
    const propIndex = new Map(); // old 1-based index -> new index, or 0 when dropped
    let nextIndex = 1;
    props.forEach((p, k) => {
      const name = { udes: 'Description', crtt: 'Creation time', mdft: 'Modification time' }[p.type];
      if (!name) { propIndex.set(k + 1, nextIndex++); return; }
      propIndex.set(k + 1, 0);
      const det = [];
      if (p.type === 'udes') {
        let q = p.body + 4;
        for (const f of ['Language', 'Name', 'Description', 'Tags']) { const c = cstr(d, q, p.end); if (c.s && f !== 'Language') det.push(f + ': ' + c.s); q = c.next; }
      } else if (p.end - p.body >= 12) {
        // Microseconds since 1904-01-01 UTC.
        const us = Number(new DataView(d.buffer, d.byteOffset + p.body + 4, 8).getBigUint64(0));
        const t = new Date(Date.UTC(1904, 0, 1) + us / 1000);
        if (!isNaN(t)) det.push(t.toISOString().replace('T', ' ').slice(0, 19) + ' UTC');
      }
      found.push({ type: name, detail: det });
      rc.meta(p.start, p.type, name, p.end - p.start, true, det.join(' · '));
    });
    const dropProps = [...propIndex.values()].includes(0);

    // Top-level uuid boxes that hold content credentials or XMP go too.
    const dropTop = new Set();
    for (const b of top) {
      if (b.type === 'uuid' && (b.uuid === C2PA_UUID || b.uuid === XMP_UUID)) {
        const name = b.uuid === C2PA_UUID ? 'C2PA / JUMBF' : 'XMP';
        const det = aiSignals(ascii(d.subarray(b.body, b.end)));
        found.push({ type: name, detail: det });
        rc.meta(b.start, 'uuid', name, b.end - b.start, true, det.join(' · '));
        dropTop.add(b);
      }
    }

    // Excise ranges from a byte span; returns kept pieces as [oldStart, oldEnd].
    const pieces = (start, end, cuts) => {
      const out = [];
      let p = start;
      for (const [a, b] of cuts) { if (b <= start || a >= end) continue; if (a > p) out.push([p, a]); p = Math.max(p, b); }
      if (p < end) out.push([p, end]);
      return out;
    };
    const idatPieces = idat ? pieces(0, idat.end - idat.body, cutsIdat) : [];
    const mapIn = (list, pos) => { // old position -> new position within the rebuilt span
      for (const [a, b, n] of list) if (pos >= a && pos < b) return n + (pos - a);
      return null;
    };
    const idatMap = []; { let n = 0; for (const [a, b] of idatPieces) { idatMap.push([a, b, n]); n += b - a; } }

    // Rebuilt tables (offsets filled in once the layout is known)
    const ref = kid('iref');
    function buildIref() {
      const v = d[ref.body];
      const idSize = v === 0 ? 2 : 4;
      const w = writer().bytes(d.subarray(ref.body, ref.body + 4));
      for (const r of boxes(d, ref.body + 4, ref.end)) {
        const rv = new DataView(d.buffer, d.byteOffset + r.body, r.end - r.body);
        let q = 0;
        const from = readUint(rv, q, idSize); q += idSize;
        const cnt = rv.getUint16(q); q += 2;
        const to = [];
        for (let k = 0; k < cnt; k++) { to.push(readUint(rv, q, idSize)); q += idSize; }
        if (removeIds.has(from)) continue;
        const keep = to.filter((t) => !removeIds.has(t));
        if (!keep.length) continue;
        const bw = writer().uint(from, idSize).uint(keep.length, 2);
        for (const t of keep) bw.uint(t, idSize);
        w.bytes(box(r.type, bw.done()));
      }
      return box('iref', w.done());
    }
    function buildIinf() {
      const kept = [...items].filter(([id]) => !removeIds.has(id));
      const w = writer().bytes(d.subarray(iinf.body, iinf.body + 4)).uint(kept.length, iinfCountSize);
      for (const [, it] of kept) w.bytes(it.raw);
      return box('iinf', w.done());
    }
    function buildIprp() {
      const iprp = kid('iprp');
      const w = writer();
      for (const p of boxes(d, iprp.body, iprp.end)) {
        if (p.type === 'ipco' && dropProps) { w.bytes(box('ipco', concat(props.filter((x, k) => propIndex.get(k + 1)).map((x) => d.subarray(x.start, x.end))))); continue; }
        if (p.type !== 'ipma') { w.bytes(d.subarray(p.start, p.end)); continue; }
        const v = d[p.body], flags = d[p.body + 3];
        const idSize = v < 1 ? 2 : 4, aSize = flags & 1 ? 2 : 1;
        let q = p.body + 4;
        const count = dv.getUint32(q); q += 4;
        const entries = [];
        for (let k = 0; k < count; k++) {
          const s = q;
          const id = readUint(dv, q, idSize); q += idSize;
          const n = d[q]; q += 1;
          const assoc = [];
          for (let a = 0; a < n; a++, q += aSize) {
            const raw = readUint(dv, q, aSize), mask = aSize === 2 ? 0x7fff : 0x7f;
            const to = propIndex.size ? propIndex.get(raw & mask) : raw & mask;
            if (to !== 0) assoc.push((raw & ~mask) | (to === undefined ? raw & mask : to));
          }
          if (removeIds.has(id) || (!assoc.length && n)) continue;
          if (!dropProps) { entries.push(d.subarray(s, q)); continue; }
          const ew = writer().uint(id, idSize).uint(assoc.length, 1);
          for (const a of assoc) ew.uint(a, aSize);
          entries.push(ew.done());
        }
        w.bytes(box('ipma', concat([d.subarray(p.body, p.body + 4), writer().uint(entries.length, 4).done(), ...entries])));
      }
      return box('iprp', w.done());
    }
    function buildIloc(mapFile) {
      const kept = locs.filter((l) => !removeIds.has(l.id));
      const w = writer().bytes(d.subarray(iloc.body, iloc.body + 6)).uint(kept.length, lv < 2 ? 2 : 4);
      for (const l of kept) {
        w.uint(l.id, lv < 2 ? 2 : 4);
        if (lv >= 1) w.uint(l.method, 2);
        w.uint(l.dataRef, 2);
        // New absolute position of each extent; base is re-anchored to the first one when it has a field.
        const abs = l.extents.map((e) => {
          if (l.method === 2 || e.len === 0 && l.method !== 0) return l.base + e.off;
          const old = l.base + e.off;
          const n = l.method === 1 ? mapIn(idatMap, old) : mapFile(old);
          if (n === null) throw new Error('Unsupported HEIF layout (image data outside the media data)');
          return n;
        });
        let base = l.base;
        if (l.method !== 2) {
          if (baseSize) base = abs.length ? Math.min(...abs) : 0;
          else base = 0;
          if (!offSize && abs.some((a) => a !== base)) throw new Error('Unsupported HEIF layout (item offsets have no room to move)');
        }
        w.uint(base, baseSize).uint(l.extents.length, 2);
        l.extents.forEach((e, k) => {
          w.uint(e.index, idxSize);
          w.uint(l.method === 2 ? e.off : abs[k] - base, offSize);
          w.uint(e.len, lenSize);
        });
      }
      return box('iloc', w.done());
    }
    function buildMeta(mapFile) {
      const parts = [metaHead];
      for (const c of kids) {
        if (c.type === 'iinf') parts.push(buildIinf());
        else if (c.type === 'iloc') parts.push(buildIloc(mapFile));
        else if (c.type === 'iref') parts.push(buildIref());
        else if (c.type === 'iprp') parts.push(buildIprp());
        else if (c.type === 'idat') parts.push(box('idat', concat(idatPieces.map(([a, b]) => d.subarray(idat.body + a, idat.body + b)))));
        else parts.push(d.subarray(c.start, c.end));
      }
      return box('meta', concat(parts));
    }

    // Layout pass: sizes don't depend on offset values (field widths are fixed), so measure first, then fill in.
    const mdatPieces = new Map(mdats.map((m) => [m, pieces(m.body, m.end, cutsFile)]));
    const sizeOf = (b) => {
      if (b === metaBox) return buildMeta(() => 0).length;
      if (b.type === 'mdat') { const len = mdatPieces.get(b).reduce((s, [x, y]) => s + y - x, 0); return (8 + len <= 0xffffffff ? 8 : 16) + len; }
      return b.end - b.start;
    };
    const fileMap = [];
    let pos = 0;
    for (const b of top) {
      if (dropTop.has(b)) continue;
      const size = sizeOf(b);
      if (b.type === 'mdat') {
        let n = pos + (size - mdatPieces.get(b).reduce((s, [x, y]) => s + y - x, 0));
        for (const [x, y] of mdatPieces.get(b)) { fileMap.push([x, y, n]); n += y - x; }
      } else if (b !== metaBox) fileMap.push([b.start, b.end, pos]);
      pos += size;
    }
    const mapFile = (p) => mapIn(fileMap, p);

    // Assemble
    const out = [];
    for (const b of top) {
      if (dropTop.has(b)) continue;
      if (b === metaBox) { out.push(buildMeta(mapFile)); rc.meta(b.start, 'meta', 'Item index (meta)', b.end - b.start, false, 'rewritten without the metadata items'); }
      else if (b.type === 'mdat') { out.push(box('mdat', concat(mdatPieces.get(b).map(([x, y]) => d.subarray(x, y))))); rc.image(b.start, b.end - b.start); }
      else { out.push(d.subarray(b.start, b.end)); if (b.type === 'ftyp') rc.meta(b.start, 'ftyp', 'File type (ftyp)', b.end - b.start, false); else rc.image(b.start, b.end - b.start); }
    }
    const bytes = concat(out);
    if (bytes.length !== pos) throw new Error('HEIF layout mismatch');

    // Report the colour profile and the primary image size, as for other formats.
    const info = heifInfo(d, kids, items);
    if (info.icc) rc.meta(info.icc.start, 'colr', 'ICC colour profile', info.icc.size, false);
    const brands = ascii(d.subarray(8, 12)) + ascii(d.subarray(16, top[0].end));
    rc.rows.sort((a, b) => parseInt(a.offset, 16) - parseInt(b.offset, 16));
    const keptRanges = keepFile.concat(keepIdat.map(([a, b]) => [a + idatStart, b + idatStart]));
    return { bytes, found, segments: rc.rows, exifItems, keptRanges, width: info.width, height: info.height, heifKind: /avif|avis/.test(brands) && !/heic|heix/.test(brands) ? 'avif' : 'heic' };
  }

  // Primary item size (ispe, swapped for 90°/270° irot) and the ICC colour profile, from ipco/ipma.
  function heifInfo(d, kids, items) {
    const dv = new DataView(d.buffer, d.byteOffset, d.byteLength);
    const out = { width: 0, height: 0, icc: null };
    try {
      const pitm = kids.find((b) => b.type === 'pitm');
      const iprp = kids.find((b) => b.type === 'iprp');
      if (!pitm || !iprp) return out;
      const primary = d[pitm.body] === 0 ? dv.getUint16(pitm.body + 4) : dv.getUint32(pitm.body + 4);
      const parts = boxes(d, iprp.body, iprp.end);
      const ipco = parts.find((b) => b.type === 'ipco');
      const props = ipco ? boxes(d, ipco.body, ipco.end) : [];
      const icc = props.find((p) => p.type === 'colr' && /^(prof|rICC)$/.test(ascii(d.subarray(p.body, p.body + 4))));
      if (icc) out.icc = { start: icc.start, size: icc.end - icc.start };
      for (const p of parts.filter((b) => b.type === 'ipma')) {
        const v = d[p.body], flags = d[p.body + 3];
        const idSize = v < 1 ? 2 : 4, aSize = flags & 1 ? 2 : 1;
        let q = p.body + 4;
        const count = dv.getUint32(q); q += 4;
        for (let k = 0; k < count; k++) {
          const id = readUint(dv, q, idSize); q += idSize;
          const n = d[q]; q += 1;
          for (let a = 0; a < n; a++) {
            const idx = (aSize === 2 ? dv.getUint16(q) & 0x7fff : d[q] & 0x7f) - 1; q += aSize;
            if (id !== primary || !props[idx]) continue;
            const pr = props[idx];
            if (pr.type === 'ispe') { out.width = dv.getUint32(pr.body + 4); out.height = dv.getUint32(pr.body + 8); }
            if (pr.type === 'irot' && (d[pr.body] & 1)) out.rotated = true;
          }
        }
      }
      if (out.rotated) [out.width, out.height] = [out.height, out.width];
    } catch (_) { /* size is only informative */ }
    return out;
  }

  // HEIF with a partial EXIF mode: the rewritten EXIF is padded to its old length and written over the
  // original bytes, so no offsets move; then the file is cleaned as usual with that item kept.
  function heifClean(d, mode) {
    const r = stripHeif(d, null);
    const fieldsOf = (x) => (x.exifItems[0] ? exifFields(x.exifItems[0].tiff) : []);
    if (mode === 'all' || !r.exifItems.length) { r.exifFields = fieldsOf(r); return r; }
    const p = d.slice();
    const keep = new Map();
    for (const it of r.exifItems) {
      const repl = exifFor(it.tiff, mode);
      if (!repl) continue;
      if (repl.length > it.tiff.length) throw new Error('Unsupported HEIF layout (EXIF cannot be rewritten in place)');
      const fill = new Uint8Array(it.tiff.length);
      fill.set(repl);
      // Map body positions to file positions across the item's extents.
      let pos = 0, k = 0;
      for (const [a, b] of it.ranges) {
        for (let x = a; x < b; x++, pos++) {
          if (pos < it.tiffAt) continue;
          if (r.keptRanges.some(([s, e]) => x >= s && x < e)) throw new Error('Unsupported HEIF layout (EXIF shares bytes with the image)');
          p[x] = fill[k++];
        }
      }
      keep.set(it.id, EXIF_KEPT_LABEL[mode]);
    }
    if (!keep.size) { r.exifFields = fieldsOf(r); return r; }
    const out = stripHeif(p, keep);
    out.found = r.found;
    out.exifFields = fieldsOf(r);
    return out;
  }

  function sniff(d) {
    if (d[0] === 0xff && d[1] === 0xd8) return 'jpeg';
    if (startsWith(d, '\x89PNG\r\n\x1a\n')) return 'png';
    if (startsWith(d, 'RIFF') && ascii(d.subarray(8, 12)) === 'WEBP') return 'webp';
    if (ascii(d.subarray(4, 8)) === 'ftyp' && /heic|heix|heim|heis|mif1|msf1|avif|avis/.test(ascii(d.subarray(8, Math.min(d.length, 64))))) return 'heif';
    return null;
  }

  // opts.exif: 'all' (default), 'gps' or 'camera'; see exifFor.
  function clean(input, opts) {
    // A plain Uint8Array view: on a Node Buffer, .slice() would share memory and edits would reach the caller's bytes.
    const d = input instanceof Uint8Array ? new Uint8Array(input.buffer, input.byteOffset, input.byteLength) : new Uint8Array(input);
    const kind = sniff(d);
    if (!kind) throw new Error('Unsupported format. JPEG, PNG, WebP, HEIC and AVIF only.');
    const o = { exif: (opts && opts.exif) || 'all' };
    if (kind === 'heif') { const r = heifClean(d, o.exif); return Object.assign(r, { kind: r.heifKind }); }
    const r = kind === 'jpeg' ? stripJpeg(d, o) : kind === 'png' ? stripPng(d, o) : stripWebp(d, o);
    return Object.assign(r, { kind });
  }

  /* ---------- diagnosis: why a platform might label this file, in plain words ---------- */
  const AI_SOURCE = ['trainedAlgorithmicMedia', 'compositeWithTrainedAlgorithmicMedia', 'algorithmicMedia', 'compositeSynthetic'];
  const AI_TOOL_NAMES = ['OpenAI', 'ChatGPT', 'DALL-E', 'Firefly', 'Gemini', 'Imagen', 'Meta AI', 'Bing Image Creator', 'Midjourney', 'Stable Diffusion', 'ComfyUI', 'Galaxy AI'];
  // level: 'ai'      — the file itself records AI generation or AI editing
  //        'history' — it carries an edit history / content credentials, but no explicit AI claim
  //        'privacy' — nothing about AI, but camera / location / software data
  //        'clean'   — nothing removable
  function diagnose(res) {
    const all = res.found.flatMap((f) => f.detail);
    const text = all.join(' · ');
    const dst = (text.match(/DigitalSourceType = (\w+)/) || [])[1] || '';
    const tools = [...new Set((text.match(/mentions ([^·]+)/g) || []).flatMap((m) => m.replace('mentions ', '').split(',').map((s) => s.trim())))];
    const aiTools = tools.filter((t) => AI_TOOL_NAMES.includes(t));
    const has = (t) => res.found.some((f) => f.type === t);
    const prompt = res.found.some((f) => /Stable Diffusion prompt|ComfyUI/.test(f.detail.join(' ')));
    const privacy = all.filter((d) => /^(GPS location|Camera: |Software: )/.test(d));
    const reasons = [];
    if (dst) reasons.push('Its DigitalSourceType field says it was ' + (sourceTypeMeaning(dst) || dst) + ' (' + dst + ').');
    if (has('C2PA / JUMBF')) reasons.push('It carries content credentials (C2PA)' + (tools.length ? ' that name ' + tools.join(', ') : '') + '.');
    else if (aiTools.length) reasons.push('Its metadata names ' + aiTools.join(', ') + '.');
    if (prompt) reasons.push('It contains the AI prompt used to generate it.');
    const gps = privacy.includes('GPS location');
    const shown = privacy.map((p) => p.replace('Camera: ', 'camera ').replace('Software: ', 'software ').replace('GPS location', 'the GPS location where it was taken'));
    // HEIF keeps capture time and captions as item properties rather than EXIF.
    if (has('Creation time') || has('Modification time')) shown.push('when it was taken or edited');
    if (has('Description')) shown.push('a title, caption or tags');
    if (shown.length) reasons.push((dst || has('C2PA / JUMBF') || aiTools.length ? 'It also reveals: ' : 'It reveals: ') + shown.join(', ') + '.');

    let level = 'clean';
    if (AI_SOURCE.includes(dst) || aiTools.length || prompt) level = 'ai';
    else if (has('C2PA / JUMBF') || dst) level = 'history';
    else if (res.found.length) level = 'privacy';

    const titles = {
      ai: 'This file says AI was involved — that is likely why it was labeled.',
      history: 'This file carries an edit history that platforms can read.',
      privacy: gps ? 'Nothing in this file points to AI. It does reveal where it was taken.' : 'Nothing in this file points to AI. It does carry device details.',
      clean: 'This file is clean. If it still gets labeled, the label is not coming from its metadata.'
    };
    if (level === 'privacy' && !privacy.length) titles.privacy = 'Nothing in this file points to AI. It carries other metadata.';
    // facts let other languages build their own sentences (see assets/i18n.js).
    const facts = {
      sourceType: dst, c2pa: has('C2PA / JUMBF'), tools, aiTools, prompt, gps,
      camera: (privacy.find((p) => p.startsWith('Camera: ')) || '').slice(8),
      software: (privacy.find((p) => p.startsWith('Software: ')) || '').slice(10)
    };
    return { level, title: titles[level], reasons, sourceType: dst, tools, facts };
  }

  const api = { clean, sniff, sourceTypeMeaning, diagnose, exifFieldKept };
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
  else root.MetaStrip = api;
